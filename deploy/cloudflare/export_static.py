#!/usr/bin/env python3
"""Turn a published + prerendered server folder into a plain static site for Cloudflare.

Usage: export_static.py <publish-dir> <output-dir>

<publish-dir> is the output of `dotnet publish BlazorWasmRegex/Server` after
`dotnet BlazorWasmRegex.Server.dll --PrerenderTo prerendered` ran in it.

The server normally serves files through MapStaticAssets, which maps every URL
(including fingerprinted ones such as css/app.21u4w5qu5m.css) to a file on disk using
BlazorWasmRegex.Server.staticwebassets.endpoints.json. A static host only serves real
files, so this script writes each URL as a file, adds the prerendered pages and the
generated _framework/resource-collection scripts, and copies _headers.

Precompressed .br/.gz variants are skipped: Cloudflare compresses responses itself.
"""
import json
import shutil
import sys
from pathlib import Path

ENDPOINTS = "BlazorWasmRegex.Server.staticwebassets.endpoints.json"
PAGES = {"index.html", "about.html", "404.html"}


def main(publish: Path, out: Path) -> int:
    wwwroot = publish / "wwwroot"
    prerendered = publish / "prerendered"
    endpoints = json.loads((publish / ENDPOINTS).read_text(encoding="utf-8"))["Endpoints"]

    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    copied = 0
    for e in endpoints:
        route = e["Route"]
        encoded = any(s["Name"] == "Content-Encoding" for s in e.get("Selectors", []))
        if encoded or route.endswith((".br", ".gz")):
            continue
        source = wwwroot / e["AssetFile"]
        target = out / route
        if target.exists():
            continue
        if not source.is_file():
            print(f"missing asset for {route}: {source}", file=sys.stderr)
            return 1
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target)
        copied += 1

    for page in PAGES:
        source = prerendered / page
        if not source.is_file():
            print(f"missing prerendered page: {source}", file=sys.stderr)
            return 1
        shutil.copyfile(source, out / page)

    # Generated by the server at runtime, saved by the prerender step.
    framework = prerendered / "_framework"
    for script in sorted(framework.glob("resource-collection*.js")):
        shutil.copyfile(script, out / "_framework" / script.name)
        # The import map also lists "<name>.gz"; the server answers it with the same script
        # (gzip-encoded). Here it is the plain script, served as JavaScript via _headers.
        shutil.copyfile(script, out / "_framework" / (script.name + ".gz"))

    shutil.copyfile(Path(__file__).with_name("_headers"), out / "_headers")

    files = sum(1 for p in out.rglob("*") if p.is_file())
    print(f"Exported {files} files ({copied} static assets) to {out}")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        sys.exit(2)
    sys.exit(main(Path(sys.argv[1]), Path(sys.argv[2])))
