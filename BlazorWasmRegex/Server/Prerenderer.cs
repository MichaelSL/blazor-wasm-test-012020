#nullable enable
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Net;
using System.Net.Http;
using System.Threading.Tasks;
using Microsoft.AspNetCore.Builder;
using Microsoft.AspNetCore.Hosting.Server;
using Microsoft.AspNetCore.Hosting.Server.Features;
using Microsoft.Extensions.DependencyInjection;

namespace BlazorWasmRegex.Server;

/// <summary>
/// Renders every page of the running app to static HTML files (<c>--PrerenderTo &lt;dir&gt;</c>).
/// Runs at image build time on the build machine; the result is served by <see cref="StaticPages"/>.
/// </summary>
public static class Prerenderer
{
    /// <summary>Fetches each page from the started <paramref name="app"/> and writes it to <paramref name="outputDirectory"/>.</summary>
    /// <returns>0 on success, 1 if any page failed.</returns>
    public static async Task<int> RunAsync(WebApplication app, string outputDirectory)
    {
        var baseAddress = app.Services.GetRequiredService<IServer>().Features.Get<IServerAddressesFeature>()!.Addresses.First();
        var origin = new Uri(baseAddress).GetLeftPart(UriPartial.Authority);
        Directory.CreateDirectory(outputDirectory);

        using var http = new HttpClient(new HttpClientHandler { AllowAutoRedirect = false }) { BaseAddress = new Uri(origin) };
        var failed = false;
        var frameworkFiles = new HashSet<string>();

        foreach (var (route, file) in StaticPages.Pages.Append((StaticPages.NotFoundRoute, StaticPages.NotFoundFile)))
        {
            using var response = await http.GetAsync(route);
            var html = await response.Content.ReadAsStringAsync();

            string? error = null;
            if (response.StatusCode != HttpStatusCode.OK)
                error = $"returned {(int)response.StatusCode}";
            else if (!html.StartsWith("<!DOCTYPE html>", StringComparison.OrdinalIgnoreCase))
                error = "is not a full HTML document";
            // Anything derived from the request URL (e.g. NavigationManager.BaseUri) would point
            // at this temporary server in the saved page.
            else if (html.Contains(origin, StringComparison.OrdinalIgnoreCase) || html.Contains("localhost", StringComparison.OrdinalIgnoreCase))
                error = $"contains the prerender server's address ({origin})";

            if (error is not null)
            {
                Console.Error.WriteLine($"Prerender: {route} {error}.");
                failed = true;
                continue;
            }

            var path = Path.Combine(outputDirectory, file);
            await File.WriteAllTextAsync(path, html);
            Console.WriteLine($"Prerender: {route} -> {path} ({html.Length:N0} chars)");
            frameworkFiles.UnionWith(StaticPages.FindGeneratedFrameworkFiles(html));
        }

        // Generated by MapRazorComponents, not in wwwroot. Saved byte for byte: the import map pins them by SRI hash.
        if (frameworkFiles.Count == 0)
        {
            Console.Error.WriteLine("Prerender: no _framework/resource-collection*.js reference found; the WebAssembly runtime could not start.");
            failed = true;
        }
        var frameworkDirectory = Path.Combine(outputDirectory, StaticPages.FrameworkDirectoryName);
        Directory.CreateDirectory(frameworkDirectory);
        foreach (var file in frameworkFiles)
        {
            using var response = await http.GetAsync("/" + file);
            if (response.StatusCode != HttpStatusCode.OK)
            {
                Console.Error.WriteLine($"Prerender: /{file} returned {(int)response.StatusCode}.");
                failed = true;
                continue;
            }
            var bytes = await response.Content.ReadAsByteArrayAsync();
            var path = Path.Combine(frameworkDirectory, Path.GetFileName(file));
            await File.WriteAllBytesAsync(path, bytes);
            Console.WriteLine($"Prerender: /{file} -> {path} ({bytes.Length:N0} bytes)");
        }

        return failed ? 1 : 0;
    }
}
